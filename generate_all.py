import os

os.makedirs('public', exist_ok=True)

with open('server.js', 'w', encoding='utf-8') as f:
    f.write("const express = require('express'), path = require('path'), fs = require('fs'), app = express();\n")
    f.write("app.use(express.json({limit: '50mb'}));\n")
    f.write("app.use(express.urlencoded({extended: true, limit: '50mb'}));\n")
    f.write("app.use((req, res, next) => { res.setHeader('Cache-Control', 'no-store, no-cache, must-revalidate'); next(); });\n")
    f.write("const DATA_FILE = path.join(__dirname, 'data.json');\n")
    f.write("if (!fs.existsSync(DATA_FILE)) fs.writeFileSync(DATA_FILE, '[]', 'utf-8');\n")
    f.write("app.get('/api/predmeti', (req, res) => {\n")
    f.write("  try { res.json(JSON.parse(fs.readFileSync(DATA_FILE, 'utf-8') || '[]')); }\n")
    f.write("  catch(e) { res.json([]); }\n")
    f.write("});\n")
    f.write("app.post('/api/predmeti', (req, res) => {\n")
    f.write("  try {\n")
    f.write("    let list = JSON.parse(fs.readFileSync(DATA_FILE, 'utf-8') || '[]');\n")
    f.write("    let p = req.body;\n")
    f.write("    if (p.id) {\n")
    f.write("      let i = list.findIndex(x => x.id == p.id);\n")
    f.write("      if (i !== -1) list[i] = p; else list.push(p);\n")
    f.write("    } else {\n")
    f.write("      p.id = Date.now();\n")
    f.write("      list.push(p);\n")
    f.write("    }\n")
    f.write("    fs.writeFileSync(DATA_FILE, JSON.stringify(list, null, 2), 'utf-8');\n")
    f.write("    res.json({success: true});\n")
    f.write("  } catch(e) { res.status(500).json({error: e.message}); }\n")
    f.write("});\n")
    f.write("app.post('/api/obrisi', (req, res) => {\n")
    f.write("  try {\n")
    f.write("    let list = JSON.parse(fs.readFileSync(DATA_FILE, 'utf-8') || '[]');\n")
    f.write("    list = list.filter(x => x.id != req.body.id);\n")
    f.write("    fs.writeFileSync(DATA_FILE, JSON.stringify(list, null, 2), 'utf-8');\n")
    f.write("    res.json({success: true});\n")
    f.write("  } catch(e) { res.status(500).json({error: e.message}); }\n")
    f.write("});\n")
    f.write("app.use(express.static(path.join(__dirname, 'public')));\n")
    f.write("app.listen(5000, () => console.log('🚀 SERVER RADI NA PORTU 5000'));\n")

print("✅ Server generiran bez prekida!")
